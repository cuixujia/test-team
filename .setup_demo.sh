> 演示 PRD：仅供 .selftest.sh / .setup_demo.sh 做脚本正负面回归；章节与真实项目无关。

## 1 系统概述

系统名称：风险管理演示系统。
模块划分说明：登记与审核两个业务模块。
功能矩阵总表：新增风险、审核处理两项业务功能。

## 4 功能需求

风险名称必填，长度不超过 50 个字符。
风险等级分为高、中、低三档，默认选中。
提交人仅可修改自己创建的风险。
项目成员仅可查看本项目的风险。
普通测试人员只能查看自己创建的风险。
提交时校验审核人身份，未认证账号提交被拒绝。
风险状态初始为待审核。
审核通过后状态变更为已审核；审核不通过则退回，状态为已关闭。
MD

